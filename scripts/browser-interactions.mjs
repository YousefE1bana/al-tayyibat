import fs from 'node:fs/promises';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';

const base=process.env.QA_BASE_URL || 'http://127.0.0.1:4173/al-tayyibat/';
const out='output/playwright/interactions';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const checks=[];
const check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
try {
  const context=await browser.newContext({viewport:{width:820,height:1000},reducedMotion:'reduce',serviceWorkers:'block'});
  const page=await context.newPage();
  await page.goto(`${base}#/foods`,{waitUntil:'networkidle'});
  await page.locator('main h1').waitFor();
  check(await page.getByRole('button',{name:'الفلاتر',exact:true}).isVisible(),'Tablet filter disclosure');
  await page.getByRole('button',{name:'الفلاتر',exact:true}).click();
  await page.screenshot({path:`${out}/tablet-filters.png`});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Tablet overflow');
  await page.goto(`${base}#/`,{waitUntil:'networkidle'});
  await page.locator('main h1').waitFor();
  const url=page.url();
  await page.keyboard.press('Tab');
  check(await page.getByRole('link',{name:'تخطَّ إلى المحتوى'}).evaluate(e=>e===document.activeElement),'Skip link first keyboard stop');
  await page.keyboard.press('Enter');
  check(await page.locator('main').evaluate(e=>e===document.activeElement)&&page.url()===url,'Skip link focus and route preservation');
  await page.keyboard.press('Control+k');
  const dialog=page.getByRole('dialog');
  await dialog.waitFor();
  check(await dialog.locator('input').evaluate(e=>e===document.activeElement),'Command palette input focus');
  const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  check(a11y.violations.length===0,'Command palette accessibility');
  await page.keyboard.press('Shift+Tab');
  check(await dialog.evaluate(e=>e.contains(document.activeElement)),'Command palette keyboard focus trap');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  check(await page.locator('main').evaluate(e=>e===document.activeElement),'Command palette focus restoration');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(`${base}#/print`,{waitUntil:'networkidle'});
  await page.locator('main h1').waitFor();
  await page.emulateMedia({media:'print'});
  check(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor==='rgb(255, 255, 255)'),'White paper print background');
  check(!(await page.locator('header').first().isVisible()),'Print header hidden');
  await page.screenshot({path:`${out}/print-preview.png`});
  await page.pdf({path:`${out}/guide.pdf`,format:'A4',printBackground:true});
  await page.emulateMedia({media:'screen',reducedMotion:'no-preference'});
  await page.goto(`${base}#/recipes`,{waitUntil:'networkidle'});
  await page.locator('main h1').waitFor();
  await page.emulateMedia({reducedMotion:'reduce'});
  check(await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches),'Live reduced motion preference');
  check(await page.locator('[inert]').count()>0,'Collapsed recipes excluded from keyboard');
  const expand=page.getByRole('button',{name:'المكونات والخطوات',exact:true}).first();
  await expand.click();
  check(await page.locator('button[aria-expanded="true"]').count()>0,'Recipe expansion');
  await page.setViewportSize({width:390,height:1000});
  await page.goto(`${base}#/ingredients`,{waitUntil:'networkidle'});
  await page.locator('#ingredients-box').fill('أرز بسمتي،أرز بسمتي؛سبيرولينا\nحلوى خل التفاح\nzzzxqv');
  await page.getByText('4 مكوّن في القائمة',{exact:true}).waitFor();
  check(await page.locator('a[href="#/foods/basmati-rice"]').count()===1,'Ingredient delimiter parsing and deduplication');
  check(await page.locator('a[href="#/foods/spirulina"]').count()===1&&await page.locator('a[href="#/foods/apple-cider-gummies"]').count()===1,'Ingredient unknown and disputed food links');
  check((await page.locator('main').innerText()).includes('غير موجود في قاعدة بيانات الدليل حتى الآن.'),'Unmatched ingredient remains unresolved');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Ingredient results mobile overflow');
  await page.screenshot({path:`${out}/ingredient-results.png`});
  await page.getByRole('button',{name:'مسح',exact:true}).click();
  check(await page.locator('#ingredients-box').inputValue()===''&&await page.getByRole('region',{name:'نتائج فحص المكونات'}).count()===0,'Ingredient clear action');
  await page.route('**/images/foods/pasta.jpg',route=>route.fulfill({status:404,body:'Intentional missing-image test'}));
  await page.goto(`${base}#/foods/pasta`,{waitUntil:'networkidle'});
  await page.locator('main [role="img"]').waitFor();
  check(await page.locator('main img[src$="/pasta.jpg"]').count()===0,'Missing image renders accessible fallback');
  await page.unroute('**/images/foods/pasta.jpg');
} finally {await fs.writeFile(`${out}/report.json`,JSON.stringify({base,checks},null,2));await browser.close();}
console.log(JSON.stringify({checks}));
