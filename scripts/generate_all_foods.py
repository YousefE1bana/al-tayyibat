# Load existing foods
foods_file = 'src/data/foods.ts'
content = open(foods_file, encoding='utf-8').read()
existing_ids = set(re.findall(r'id:\s*"([^"]+)"', content))
print(f"Loaded {len(existing_ids)} existing food IDs.")

new_foods = []
new_ids = set()

def add_food(
    food_id,
    name,
    aliases,
    category_id,
    status,
    short_desc,
    explanation,
    usage="",
    restrictions=None,
    alternatives=None,
    related_foods=None,
    source_ids=None,
    provenance=None,
    notes=None
):
    if food_id in existing_ids or food_id in new_ids:
        print(f"Skipping duplicate ID: {food_id}")
        return

    if category_id not in VALID_CATEGORIES:
        raise ValueError(f"Invalid categoryId '{category_id}' for food '{food_id}'")

    s_ids = source_ids or [G, R]
    for sid in s_ids:
        if sid not in VALID_SOURCES:
            raise ValueError(f"Invalid sourceId '{sid}' in food '{food_id}'")

    prov = provenance or [
        {
            "sourceId": G,
            "level": "indirect",
            "section": "قواعد الأطعمة والمشتقات",
            "note": "مشتق وفق قواعد نظام الطيبات المعتمدة"
        }
    ]
    for p in prov:
        if p["sourceId"] not in VALID_SOURCES:
            raise ValueError(f"Invalid provenance sourceId '{p['sourceId']}' in food '{food_id}'")

    item = {
        "id": food_id,
        "slug": food_id,
        "name": name,
        "aliases": aliases,
        "categoryId": category_id,
        "status": status,
        "shortDescription": short_desc,
        "explanation": explanation,
        "usage": usage,
        "restrictions": restrictions or [],
        "alternatives": alternatives or [],
        "relatedFoods": related_foods or [],
        "sourceIds": s_ids,
        "provenance": prov
    }
    if notes:
        item["notes"] = notes

    new_foods.append(item)
    new_ids.add(food_id)

